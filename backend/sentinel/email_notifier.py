# Severity ordering for threshold comparison
# ---------------------------------------------------------------------------
_SEVERITY_RANK: Dict[str, int] = {
    "LOW": 1,
    "MEDIUM": 2,
    "HIGH": 3,
    "CRITICAL": 4,
}


def _severity_meets_threshold(severity: str, threshold: str) -> bool:
    """Check if a severity level meets or exceeds the threshold.

    Args:
        severity:  Playbook severity string (e.g. "CRITICAL").
        threshold: Minimum severity to trigger alert (e.g. "HIGH").

    Returns:
        True if severity >= threshold in the ranking.
    """
    sev_rank = _SEVERITY_RANK.get(severity.upper(), 0)
    thr_rank = _SEVERITY_RANK.get(threshold.upper(), 4)
    return sev_rank >= thr_rank


